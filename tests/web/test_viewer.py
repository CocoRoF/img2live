JS_EVAL = """
(sets) => {
  const { model, viewer, controller, renderer } = window.__img2live;
  viewer.setOption('idle', false); viewer.setOption('blink', false); viewer.setOption('physics', false);
  const meshes = model.meshes;
  const grab = (vals, how) => Object.fromEntries(meshes.map((m, i) => {
    const out = new Float32Array(m.positions.length);
    if (how === 'gpu') return [m.id, Array.from(renderer.debugReadPositions(i))];
    model.evaluateMesh(i, vals, out);
    return [m.id, Array.from(out)];
  }));
  const res = { direct: [], controller: [], gpu: [], opacity: [] };
  for (const s of sets) {
    res.direct.push(grab(s, 'cpu'));                       // plain {id: value} object
    viewer.resetParams();
    for (const [k, v] of Object.entries(s)) viewer.setParam(k, v);
    controller.step(0.016);                                // user -> idle/blink/physics (all off) -> clamp
    res.controller.push(grab(controller.values, 'cpu'));
    renderer.render(controller.values);                    // evaluates + uploads dirty meshes
    res.gpu.push(grab(null, 'gpu'));                       // read the GPU buffers back
    res.opacity.push(Object.fromEntries(meshes.map((m, i) => [m.id, model.opacityOf(i, controller.values)])));
  }
  viewer.resetParams();
  return res;
}
"""


def _max_err(js_meshes: dict, ref: dict) -> float:
    assert set(js_meshes) == set(ref)
    worst = 0.0
    for mid, arr in js_meshes.items():
        a = np.asarray(arr, dtype=np.float64).reshape(-1, 2)
        assert a.shape == ref[mid].shape, mid
        worst = max(worst, float(np.abs(a - ref[mid]).max()))
    return worst


def test_numeric_parity_with_python_reference(viewer):
    viewer.open()
    puppet = puppet_json()
    names = list(PARAM_SETS)
    res = viewer.page.evaluate(JS_EVAL, [PARAM_SETS[n] for n in names])
    for k, name in enumerate(names):
        ref = runtime_py.evaluate(puppet, PARAM_SETS[name])
        full = {p["id"]: p["default"] for p in puppet["params"]}
        full.update(PARAM_SETS[name])
        for path in ("direct", "controller", "gpu"):
            err = _max_err(res[path][k], ref)
            assert err < 1e-3, f"{name} via {path}: max vertex error {err:.5f} px"
        for m in puppet["meshes"]:  # opacity, incl. the mouth overlay's opacityBind
            assert res["opacity"][k][m["id"]] == pytest.approx(runtime_py.opacity_of(m, full), abs=1e-6), (name, m["id"])
    assert len(names) >= 6
    assert set(res["direct"][0]) == {m["id"] for m in puppet["meshes"]}


def test_sign_conventions(viewer):
    """+AngleX turns the head to the viewer's right, +AngleY looks up, +AngleZ tilts clockwise on screen."""
    viewer.open()
    res = viewer.page.evaluate(
        """() => {
          const { model } = window.__img2live;
          const centroid = (id, params) => { const i = model.meshIndex.get(id), o = new Float32Array(model.meshes[i].positions.length);
            model.evaluateMesh(i, params, o); let x = 0, y = 0; for (let k = 0; k < o.length; k += 2) { x += o[k]; y += o[k + 1]; }
            return [x / (o.length / 2), y / (o.length / 2)]; };
          const r = {};
          for (const id of ['nose', 'eyewhite_l', 'eyewhite_r', 'mouth']) {
            const a = centroid(id, {}), x = centroid(id, { ParamAngleX: 30 }), y = centroid(id, { ParamAngleY: 30 });
            r[id] = { dx: x[0] - a[0], dy: y[1] - a[1] };
          }
          // roll: a point above the pivot (hair top) moves right = clockwise on screen (y down)
          const top = centroid('front_hair', {}), rolled = centroid('front_hair', { ParamAngleZ: 25 });
          r.roll = { dx: rolled[0] - top[0] };
          return r;
        }"""
    )
    for mesh in ("nose", "eyewhite_l", "eyewhite_r", "mouth"):
        assert res[mesh]["dx"] > 3, (mesh, res[mesh])  # features move right for +AngleX
        assert res[mesh]["dy"] < -2, (mesh, res[mesh])  # ... and up for +AngleY
    assert res["roll"]["dx"] > 5  # hair (above the neck pivot) swings right: clockwise


def test_physics_and_idle_are_clamped_and_bounded(viewer):
    """Run the controller for a minute of simulated time with everything on: values stay in range, nothing explodes."""
    viewer.open("")
    res = viewer.page.evaluate(
        """() => {
          const { controller: c, model } = window.__img2live;
          for (const o of ['idle', 'blink', 'physics']) c.setOption(o, true);
          let bad = 0, maxHair = 0, minOpen = 1;
          const hair = model.paramIndex.get('ParamHairBack'), eye = model.paramIndex.get('ParamEyeLOpen');
          for (let t = 0; t < 60 * 60; t++) {
            if (t % 300 === 0) c.setParam('ParamAngleX', (Math.random() * 2 - 1) * 30);   // user swings the head
            const v = c.step(1 / 60);
            for (let i = 0; i < v.length; i++) if (!(v[i] >= model.mins[i] - 1e-9 && v[i] <= model.maxs[i] + 1e-9)) bad++;
            maxHair = Math.max(maxHair, Math.abs(v[hair])); minOpen = Math.min(minOpen, v[eye]);
          }
          c.reset();
          return { bad, maxHair, minOpen };
        }"""
    )
    assert res["bad"] == 0
    assert 0.05 < res["maxHair"] <= 1.0  # the hair does move, within its limit
    assert res["minOpen"] < 0.1  # at least one blink closed the eye


def test_runtime_is_importable_without_dom(tmp_path):
    """puppet-runtime.js must not touch the DOM or WebGL: load it in Node when Node is available."""
    import shutil
    import subprocess

    node = shutil.which("node")
    if not node:
        pytest.skip("node is not installed")
    mjs = tmp_path / "puppet-runtime.mjs"
    mjs.write_text((STATIC / "js" / "puppet-runtime.js").read_text(encoding="utf8"), encoding="utf8")
    script = tmp_path / "check.mjs"
    ref = runtime_py.evaluate(puppet_json(), PARAM_SETS["mixed"])
    (tmp_path / "ref.json").write_text(json.dumps({k: v.reshape(-1).tolist() for k, v in ref.items()}))
    script.write_text(
        f"""
import fs from 'fs';
import {{ PuppetModel, PuppetController }} from {json.dumps(mjs.as_uri())};
const m = new PuppetModel(JSON.parse(fs.readFileSync({json.dumps(str(SAMPLE / 'puppet.json'))}, 'utf8')));
const ref = JSON.parse(fs.readFileSync({json.dumps(str(tmp_path / 'ref.json'))}, 'utf8'));
const params = {json.dumps(PARAM_SETS['mixed'])};
let worst = 0;
m.meshes.forEach((mesh, i) => {{
  const out = new Float32Array(mesh.positions.length); m.evaluateMesh(i, params, out);
  ref[mesh.id].forEach((v, k) => {{ worst = Math.max(worst, Math.abs(v - out[k])); }});
}});
const c = new PuppetController(m, {{ seed: 1 }});
for (let t = 0; t < 600; t++) c.step(1 / 60);
console.log(JSON.stringify({{ worst, ok: typeof document === 'undefined' }}));
"""
    )
    r = subprocess.run([node, str(script)], capture_output=True, text=True, timeout=60, check=False)
    assert r.returncode == 0, r.stderr
    out = json.loads(r.stdout.strip().splitlines()[-1])
    assert out["ok"] and out["worst"] < 1e-3


