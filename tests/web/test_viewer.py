class Page:
    """A page with every console error / failed request / page error recorded."""

    def __init__(self, context, base_url):
        self.context = context
        self.base_url = base_url
        self.page = context.new_page()
        self.errors: list[str] = []
        self.warnings: list[str] = []
        p = self.page
        p.on("console", self._on_console)
        p.on("pageerror", lambda e: self.errors.append(f"pageerror: {e}"))
        p.on("requestfailed", lambda r: self.errors.append(f"requestfailed: {r.url} {r.failure}"))
        p.on("response", lambda r: self.errors.append(f"HTTP {r.status}: {r.url}") if r.status >= 400 else None)

    def _on_console(self, m):
        if m.type == "error":
            self.errors.append(f"console.error: {m.text}")
        elif m.type == "warning":
            self.warnings.append(m.text)

    def open(self, query=make_shots.QUIET, expect_ready=True):
        self.page.goto(f"{self.base_url}/viewer-test.html?{query}")
        self.page.wait_for_function("document.documentElement.dataset.ready", timeout=30000)
        if expect_ready:
            assert self.page.evaluate("document.documentElement.dataset.ready") == "1", self.page.evaluate("window.__img2liveError")
        make_shots.settle(self.page)
        return self

    def __getattr__(self, name):
        return getattr(self.page, name)


