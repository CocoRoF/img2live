class _Handler(http.server.SimpleHTTPRequestHandler):
    static_dir = ""
    sample_dir = ""

    def translate_path(self, path):  # /sample/* -> sample puppet, everything else -> static dir
        path = path.split("?", 1)[0].split("#", 1)[0]
        if path.startswith("/sample/"):
            return os.path.join(self.sample_dir, path[len("/sample/"):])
        return os.path.join(self.static_dir, path.lstrip("/"))

    def end_headers(self):
        self.send_header("Cache-Control", "no-store")
        super().end_headers()

    def log_message(self, *args):
        pass


class _Server(socketserver.ThreadingMixIn, http.server.HTTPServer):
    daemon_threads = True


def serve(static_dir: Path, sample_dir: Path):
    handler = type("Handler", (_Handler,), {"static_dir": str(static_dir), "sample_dir": str(sample_dir)})
    srv = _Server(("127.0.0.1", 0), handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv, f"http://127.0.0.1:{srv.server_address[1]}"


